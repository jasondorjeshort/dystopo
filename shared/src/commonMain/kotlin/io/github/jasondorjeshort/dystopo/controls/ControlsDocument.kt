package io.github.jasondorjeshort.dystopo.controls

import io.github.jasondorjeshort.dystopo.maplibre.JsonWriter

/**
 * ADR 0053 §2: the registry as a JSON document, `tools/demo/controls.json` in the repository (`devtool controls`
 * writes it, `./gradlew updateGoldens` runs that, a devtool test fails when the file differs), `window.DYSTOPO_CONTROLS`
 * on the live page (`injectLive`) and `/controls.json` on both servers. Format (documented in
 * `docs/reference/live-server.md` › The controls document):
 *
 * - `version`: the document format, raised on a change a reader must know about.
 * - `platforms`: per client, `zonesVersion` and `zones` (the zone vocabulary its placements use).
 * - `categories`: `id`, `title`, `order`.
 * - `items`: `id` (the phone settings key), `kind`, `type`, `choices`, `choicesByUnits` (`ft`, `m`), `default`, `min`,
 *   `max`, `syncKey`, `platforms`, and `placement` per platform: `category`, `order`, `zone`, and `elements` (web
 *   element ids carrying `data-control="<id>"`, or `maplibregl.X` for a control the page adds), `row` (the Android
 *   settings row) or `inventory` (the controls inventory's rows an Android map element holds, as `GET /layout` lists
 *   them). Absent fields are left out: an item of one client carries only `id`, `kind`, `platforms` and `placement`.
 */
object ControlsDocument {
    const val VERSION = 1
    const val FILE = "tools/demo/controls.json"

    fun json(): Map<String, Any?> = linkedMapOf(
        "about" to "One definition of the controls the clients share (ADR 0053). Generated by devtool controls " +
            "(./gradlew updateGoldens) from shared/.../controls; do not edit by hand.",
        "version" to VERSION,
        "platforms" to Platform.entries.associate { p -> p.key to linkedMapOf("zonesVersion" to p.zonesVersion, "zones" to p.zones) },
        "categories" to Controls.categories.map { linkedMapOf("id" to it.id, "title" to it.title, "order" to it.order) },
        "items" to Controls.items.map(::itemJson),
    )

    fun itemJson(item: ControlItem): Map<String, Any?> = linkedMapOf<String, Any?>().apply {
        put("id", item.id)
        put("kind", item.kind.key)
        item.type?.let { put("type", it.key) }
        if (item.choices.isNotEmpty()) put("choices", item.choices)
        if (item.choicesByUnits.isNotEmpty()) put("choicesByUnits", LinkedHashMap(item.choicesByUnits))
        if (item.default != null) put("default", item.default)
        item.min?.let { put("min", it) }
        item.max?.let { put("max", it) }
        item.syncKey?.let { put("syncKey", it) }
        put("platforms", item.platforms.map { it.key })
        put(
            "placement",
            item.placements.entries.sortedBy { it.key.ordinal }.associateTo(LinkedHashMap()) { (p, pl) ->
                p.key to linkedMapOf<String, Any?>("category" to pl.category, "order" to pl.order, "zone" to pl.zone).apply {
                    if (pl.elements.isNotEmpty()) put("elements", pl.elements)
                    pl.row?.let { put("row", it) }
                    if (pl.inventory.isNotEmpty()) put("inventory", pl.inventory)
                }
            },
        )
    }

    /** The document on one line (what `injectLive` inlines). */
    fun compact(): String = JsonWriter.write(json())

    /** The committed file's text: two-space indents, short lists on one line, a final newline. */
    fun text(): String = StringBuilder().also { pretty(it, json(), "") }.append('\n').toString()

    private fun pretty(sb: StringBuilder, v: Any?, indent: String) {
        val inner = "$indent  "
        when {
            v is Map<*, *> && v.isNotEmpty() -> {
                sb.append("{\n")
                v.entries.forEachIndexed { i, (k, value) ->
                    sb.append(inner).append(JsonWriter.write(k as String)).append(": ")
                    pretty(sb, value, inner)
                    sb.append(if (i < v.size - 1) ",\n" else "\n")
                }
                sb.append(indent).append('}')
            }
            v is List<*> && v.any { it is Map<*, *> || it is List<*> } -> {
                sb.append("[\n")
                v.forEachIndexed { i, e ->
                    sb.append(inner)
                    pretty(sb, e, inner)
                    sb.append(if (i < v.size - 1) ",\n" else "\n")
                }
                sb.append(indent).append(']')
            }
            v is List<*> -> sb.append(v.joinToString(", ", "[", "]") { JsonWriter.write(it) })
            else -> sb.append(JsonWriter.write(v))
        }
    }
}
