/**
 * [Wmm] against NOAA's published WMM2025 test values (`WMM2025_TestValues.txt` in `WMM2025COF.zip`,
 * public domain): all 100 points, 2025.0 to 2029.5, heights 0 to 98 km, poles to equator. The task
 * asks for declination within 0.1 degrees at three points; every point is held to that, and to 1 nT
 * per component (declinations are published to 0.01 degrees; the components are copied here to 0.1 nT).
 */
class WmmTest {
    @Test
    fun declinationAtThreeNamedPoints() {
        // Rows 1, 4 and 11 of the file: the high Arctic, central Asia, and the South Pacific at mid-year.
        assertEquals(-99.77, Wmm.declination(89.0, -121.0, 2025.0, 28.0), 0.1)
        assertEquals(0.50, Wmm.declination(43.0, 93.0, 2025.0, 65.0), 0.1)
        assertEquals(20.28, Wmm.declination(-36.0, -137.0, 2025.5, 6.0), 0.1)
    }

    @Test
    fun everyPublishedTestValue() {
        var worstD = 0.0
        var worstNt = 0.0
        for (v in VALUES) {
            val year = v[0]
            val alt = v[1]
            val lat = v[2]
            val lon = v[3]
            val f = Wmm.field(lat, lon, year, alt)
            val dd = abs(f.declinationDeg - v[4])
            val di = abs(f.inclinationDeg - v[5])
            val dn = maxOf(abs(f.xNt - v[6]), abs(f.yNt - v[7]), abs(f.zNt - v[8]))
            assertTrue(
                dd <= 0.1 && di <= 0.1 && dn <= 1.0,
                "at $year $alt km $lat,$lon: D ${f.declinationDeg} vs ${v[4]}, I ${f.inclinationDeg} vs ${v[5]}, X/Y/Z off by $dn nT",
            )
            worstD = maxOf(worstD, dd)
            worstNt = maxOf(worstNt, dn)
        }
        // Rounding of the published declination (0.01 degrees) is the only expected difference.
        assertTrue(worstD <= 0.006, "worst declination difference $worstD")
        assertTrue(worstNt <= 0.1, "worst component difference $worstNt nT")
    }

    @Test
    fun decimalYear() {
        assertEquals(2025.0, Wmm.decimalYear(1_735_689_600_000L), 0.01) // 2025-01-01T00:00Z
        assertEquals(2026.775, Wmm.decimalYear(1_791_590_400_000L), 0.01) // 2026-10-10T00:00Z
    }

    @Test
    fun rainierDeclinationIsAboutFifteenEast() {
        // Paradise, Mount Rainier, autumn 2026: NOAA's calculator gives about 14.9 degrees east.
        val d = Wmm.declination(46.786, -121.736, 2026.8, 1.65)
        assertTrue(d in 14.0..16.0, "declination $d")
    }

