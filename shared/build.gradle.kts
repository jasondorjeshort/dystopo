/**
 * Embeds the data source registry (src/commonMain/resources/sources.json) in commonMain as a Kotlin
 * string constant, so every target (JVM now, Android/iOS later) gets it without a resource-loading hook.
 */
val generateSourcesJson by tasks.registering {
    val input = layout.projectDirectory.file("src/commonMain/resources/sources.json")
    // T80: the Norway border mask (written by `devtool borders`) is embedded the same way, so the phone's
    // NorwaySource has it without a resource-loading hook.
    val borders = layout.projectDirectory.file("src/commonMain/resources/borders/norway-neighbours.json")
    val outDir = layout.buildDirectory.dir("generated/sourcesJson/kotlin")
    inputs.file(input)
    inputs.file(borders)
    outputs.dir(outDir)
    doLast {
        // JVM string constants are limited to 65535 bytes of modified UTF-8; split long text into chunks
        // joined at run time (a `+` of literals would be folded back into one constant).
        fun literal(text: String) = text.replace("\r\n", "\n").chunked(8000).joinToString(",\n        ") { chunk ->
            "\"" + chunk.replace("\\", "\\\\").replace("\"", "\\\"").replace("\$", "\\\$").replace("\n", "\\n") + "\""
        }
        val chunks = literal(input.asFile.readText(Charsets.UTF_8))
        val file = outDir.get().file("io/github/jasondorjeshort/dystopo/sources/SourcesJson.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "// Generated by :shared:generateSourcesJson from src/commonMain/resources/sources.json. Do not edit.\n" +
                "package io.github.jasondorjeshort.dystopo.sources\n\n" +
                "/** The built-in data source registry, verbatim from sources.json. */\n" +
                "object SourcesJson {\n    val TEXT: String = listOf(\n        $chunks,\n    ).joinToString(\"\")\n}\n",
            Charsets.UTF_8,
        )
        val borderFile = outDir.get().file("io/github/jasondorjeshort/dystopo/sources/elevation/BorderData.kt").asFile
        borderFile.parentFile.mkdirs()
        borderFile.writeText(
            "// Generated by :shared:generateSourcesJson from src/commonMain/resources/borders/. Do not edit.\n" +
                "package io.github.jasondorjeshort.dystopo.sources.elevation\n\n" +
                "/** Border masks for the national sources (BorderMask), verbatim from their JSON files. */\n" +
                "internal object BorderData {\n    val NORWAY_NEIGHBOURS: String get() = listOf(\n        ${literal(borders.asFile.readText(Charsets.UTF_8))},\n    ).joinToString(\"\")\n}\n",
            Charsets.UTF_8,
        )
    }
}

