plugins {
    alias(libs.plugins.kotlin.multiplatform)
}

/**
 * Embeds the data source registry (src/commonMain/resources/sources.json) in commonMain as a Kotlin
 * string constant, so every target (JVM now, Android/iOS later) gets it without a resource-loading hook.
 */
val generateSourcesJson by tasks.registering {
    val input = layout.projectDirectory.file("src/commonMain/resources/sources.json")
    val outDir = layout.buildDirectory.dir("generated/sourcesJson/kotlin")
    inputs.file(input)
    outputs.dir(outDir)
    doLast {
        val json = input.asFile.readText(Charsets.UTF_8).replace("\r\n", "\n")
        // JVM string constants are limited to 65535 bytes of modified UTF-8; split long text into chunks
        // joined at run time (a `+` of literals would be folded back into one constant).
        val chunks = json.chunked(8000).joinToString(",\n        ") { chunk ->
            "\"" + chunk.replace("\\", "\\\\").replace("\"", "\\\"").replace("\$", "\\\$").replace("\n", "\\n") + "\""
        }
        val file = outDir.get().file("io/github/jasondorjeshort/dystopo/sources/SourcesJson.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "// Generated by :shared:generateSourcesJson from src/commonMain/resources/sources.json. Do not edit.\n" +
                "package io.github.jasondorjeshort.dystopo.sources\n\n" +
                "/** The built-in data source registry, verbatim from sources.json. */\n" +
                "object SourcesJson {\n    val TEXT: String = listOf(\n        $chunks,\n    ).joinToString(\"\")\n}\n",
            Charsets.UTF_8,
        )
    }
}

kotlin {
    jvmToolchain(21)

    // Android and iOS targets are added in later phases. Code in commonMain must stay
    // pure Kotlin (no java.* imports) so it compiles for all of them.
    jvm()

    sourceSets {
        commonMain {
            kotlin.srcDir(generateSourcesJson)
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
        }
    }
}
